#!/usr/bin/env node
// Keeps docs/game-rules.md and the /how-to-play page in step with the contract.
//
//   node scripts/check-game-rules.mjs           check mode (CI): exits 1 on drift
//   node scripts/check-game-rules.mjs --write   regenerate the frontend constants file
//
// The source of truth is onchain/contracts/lyricsflip/src/lib.rs.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const libRsPath = path.join(root, 'onchain/contracts/lyricsflip/src/lib.rs');
const docPath = path.join(root, 'docs/game-rules.md');
const frontendPath = path.join(root, 'frontend/src/lib/game-rules.constants.ts');

// Constants shown on /how-to-play. Each must be a `pub const` in lib.rs.
const PAGE_CONSTANTS = [
  'DEFAULT_ROUND_DURATION_SECONDS',
  'DEFAULT_MAX_PLAYERS',
  'CARD_ANSWER_WINDOW_SECONDS',
  'FIRST_LEDGER_GRACE_SECONDS',
  'MAX_CORRECT_POINTS',
  'POINTS_DECAY_PER_SECOND',
  'MIN_CORRECT_POINTS',
  'LOBBY_TIMEOUT_SECONDS',
  'MAX_OPEN_ROUNDS_PER_ADDRESS',
];

function readLibConstants(source) {
  const values = new Map();
  for (const [, name, raw] of source.matchAll(/pub const ([A-Z_]+): u(?:32|64) = ([\d_]+);/g)) {
    values.set(name, Number(raw.replaceAll('_', '')));
  }
  return values;
}

// Each backticked constant is paired with the first bold number that follows
// it before the next backtick, e.g. "`NAME` is **300**" or "`MIN` (**10**) and
// `MAX` (**86 400**)". Lines can hold several pairs.
function readDocConstants(markdown) {
  const documented = new Map();
  for (const [, name, bold] of markdown.matchAll(/`([A-Z][A-Z_]+)`[^`*]*?\*\*([\d ]+)\*\*/g)) {
    if (!documented.has(name)) {
      documented.set(name, Number(bold.replaceAll(' ', '')));
    }
  }
  return documented;
}

function generateFrontendFile(libValues) {
  const lines = PAGE_CONSTANTS.map((name) => {
    if (!libValues.has(name)) throw new Error(`lib.rs has no constant ${name}`);
    return `  ${name}: ${libValues.get(name)},`;
  });
  return [
    '// Generated by scripts/check-game-rules.mjs from lib.rs. Do not edit by hand.',
    'export const GAME_RULE_CONSTANTS = {',
    ...lines,
    '} as const;',
    '',
  ].join('\n');
}

const libValues = readLibConstants(readFileSync(libRsPath, 'utf8'));
const generated = generateFrontendFile(libValues);

if (process.argv.includes('--write')) {
  writeFileSync(frontendPath, generated);
  process.stdout.write(`wrote ${path.relative(root, frontendPath)}\n`);
  process.exit(0);
}

const problems = [];

const docValues = readDocConstants(readFileSync(docPath, 'utf8'));
for (const [name, documented] of docValues) {
  if (!libValues.has(name)) {
    // Not every backticked name is a constant (e.g. function names), so only
    // report ALL_CAPS names that look like constants.
    if (/_(SECONDS|POINTS|PLAYERS|ROUNDS|CORRECT_POINTS|ADDRESS)$/.test(name)) {
      problems.push(`docs/game-rules.md documents ${name}, which lib.rs does not define`);
    }
    continue;
  }
  if (libValues.get(name) !== documented) {
    problems.push(
      `${name}: docs say ${documented}, lib.rs says ${libValues.get(name)}`,
    );
  }
}

let existing = '';
try {
  existing = readFileSync(frontendPath, 'utf8');
} catch {
  problems.push(`${path.relative(root, frontendPath)} is missing; run with --write`);
}
if (existing && existing !== generated) {
  problems.push(`${path.relative(root, frontendPath)} is stale; run with --write`);
}

if (problems.length > 0) {
  process.stderr.write(`game rules drift:\n  ${problems.join('\n  ')}\n`);
  process.exit(1);
}
process.stdout.write(`game rules agree with lib.rs (${docValues.size} documented values checked)\n`);
